// 국가당 영토 3곳. 수도권이 제일 단단하고 연안이 제일 무르다 — 신규 유저가 어디부터 깨야 할지
// 바로 보이게 하려는 난이도 배치다(기여 1회 10pt, 하루 10회 — services/neighborhoodConquest.js).
const TERRITORIES = [
  { suffix: "수도권", difficulty: 40, dLat: 0.0, dLng: 0.0 },
  { suffix: "내륙", difficulty: 30, dLat: 1.1, dLng: -1.3 },
  { suffix: "연안", difficulty: 25, dLat: -1.2, dLng: 1.4 },
];

function clampLat(lat) {
  return Math.max(-85, Math.min(85, lat));
}

// 경도는 ±180을 넘으면 지도 반대편으로 튀므로 감싸준다(날짜변경선 근처 국가 때문에 실제로 발생).
function wrapLng(lng) {
  return ((((lng + 180) % 360) + 360) % 360) - 180;
}

function seedCountriesIfMissing() {
  const insertRegion = db.prepare(
    "INSERT OR IGNORE INTO regions (id, name, status, lat, lng) VALUES (?, ?, 'dispute', ?, ?)"
  );
  const findRegion = db.prepare("SELECT id FROM regions WHERE name = ?");
  const countTerritories = db.prepare(
    "SELECT COUNT(*) AS count FROM neighborhoods WHERE parent_region_id = ?"
  );
  const insertTerritory = db.prepare(
    `INSERT OR IGNORE INTO neighborhoods (id, parent_region_id, name, status, npc_difficulty, lat, lng)
     VALUES (?, ?, ?, 'npc', ?, ?, ?)`
  );
  const insertAdjacency = db.prepare(
    "INSERT OR IGNORE INTO neighborhood_adjacency (neighborhood_id, adjacent_neighborhood_id) VALUES (?, ?)"
  );

  let newCountries = 0;
  let newTerritories = 0;

  const tx = db.transaction(() => {
    for (const [name, lat, lng] of COUNTRIES) {
      insertRegion.run(randomUUID(), name, lat, lng);
      const region = findRegion.get(name);
      if (!region) continue;

      // 이미 영토가 있는 국가는 건드리지 않는다 — 기존 도시 시드(서울/도쿄 등)의 동이나
      // 운영 중 추가된 영토를 덮어쓰지 않기 위해서다.
      if (countTerritories.get(region.id).count > 0) continue;

      const ids = TERRITORIES.map(() => randomUUID());
      TERRITORIES.forEach((t, i) => {
        insertTerritory.run(
          ids[i],
          region.id,
          `${name} ${t.suffix}`,
          t.difficulty,
          clampLat(lat + t.dLat),
          wrapLng(lng + t.dLng)
        );
      });

      // 국가 안에서 링(고리)으로 양방향 인접 등록 — 한 곳을 해방하면 나머지 둘을 공격할 수 있다.
      for (let i = 0; i < ids.length; i++) {
        const a = ids[i];
        const b = ids[(i + 1) % ids.length];
        insertAdjacency.run(a, b);
        insertAdjacency.run(b, a);
      }

      newCountries++;
      newTerritories += ids.length;
    }
  });
  tx();

  console.log(
    `[seed-pangaea] 국가 ${COUNTRIES.length}개 확인 — 신규 ${newCountries}개국 / 영토 ${newTerritories}곳 추가`
  );
}

module.exports = { seedCountriesIfMissing, COUNTRIES, TERRITORIES };
