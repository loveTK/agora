// 예전 도시 시드(서울/도쿄/…)의 동 가운데 유저 기록이 있는 것을 어느 국가·광역으로 옮길지.
const LEGACY_CITY_HOME = {
  "서울": ["대한민국", "서울"], "도쿄": ["일본", "도쿄"], "뉴욕": ["미국", "뉴욕"],
  "런던": ["영국", "런던"], "파리": ["프랑스", "일드프랑스"], "베를린": ["독일", "베를린"],
};

const clampLat = (lat) => Math.max(-85, Math.min(85, lat));
const wrapLng = (lng) => ((((lng + 180) % 360) + 360) % 360) - 180;
// 고위도에서는 경도 1도가 좁아지므로 동서 간격을 벌려 화면에서 정사각형에 가깝게 보이게 한다.
const lngScale = (lat) => Math.min(2.5, 1 / Math.max(0.35, Math.cos((lat * Math.PI) / 180)));

function buildPlan(countryName, lat, lng) {
  const real = REAL[countryName] || ADMIN1[countryName];
  if (real) {
    const order = REAL[countryName] ? DISTRICT_ORDER : DISTRICT_ORDER.slice(0, ADMIN1_DISTRICTS);
    return real.provinces.map((p, i) => {
      const prov = Array.isArray(p) ? { name: p[0], lat: p[1], lng: p[2] } : p;
      const districts = prov.districts
        ? prov.districts.map(([name, dlat, dlng]) => ({ name: `${prov.name} ${name}`, lat: dlat, lng: dlng }))
        : order.map((d) => {
            const [a, b] = DISTRICT_OFFSET[d];
            return {
              name: `${prov.name} ${d}`,
              lat: clampLat(prov.lat + a * real.spread),
              lng: wrapLng(prov.lng + b * real.spread * lngScale(prov.lat)),
            };
          });
      return { name: prov.name, lat: prov.lat, lng: prov.lng, isCapital: i === 0, districts };
    });
  }

  const tier = TIERS[TIER_OF[countryName] || "medium"];
  return PROVINCE_ORDER.slice(0, tier.provinces).map((pname, i) => {
    const [pa, pb] = PROVINCE_OFFSET[pname];
    const plat = clampLat(lat + pa * tier.R);
    const plng = wrapLng(lng + pb * tier.R * lngScale(lat));
    const districts = DISTRICT_ORDER.slice(0, tier.districts).map((d) => {
      const [a, b] = DISTRICT_OFFSET[d];
      return { name: `${pname} ${d}`, lat: clampLat(plat + a * tier.r), lng: wrapLng(plng + b * tier.r * lngScale(plat)) };
    });
    return { name: pname, lat: plat, lng: plng, isCapital: i === 0, districts };
  });
}

function seedProvincesIfMissing() {
  const findRegion = db.prepare("SELECT id FROM regions WHERE name = ?");
  const countProvinces = db.prepare("SELECT COUNT(*) AS count FROM provinces WHERE region_id = ?");
  const insertProvince = db.prepare(
    "INSERT OR IGNORE INTO provinces (id, region_id, name, lat, lng, is_capital) VALUES (?, ?, ?, ?, ?, ?)"
  );
  const insertDistrict = db.prepare(
    `INSERT OR IGNORE INTO neighborhoods (id, parent_region_id, province_id, name, status, npc_difficulty, lat, lng)
     VALUES (?, ?, ?, ?, 'npc', ?, ?, ?)`
  );
  const insertAdjacency = db.prepare(
    "INSERT OR IGNORE INTO neighborhood_adjacency (neighborhood_id, adjacent_neighborhood_id) VALUES (?, ?)"
  );
  const link = (a, b) => { insertAdjacency.run(a, b); insertAdjacency.run(b, a); };

  let newProvinces = 0;
  let newDistricts = 0;
  const unknownTier = Object.keys(TIER_OF).filter((n) => !COUNTRIES.some(([name]) => name === n));
  if (unknownTier.length) console.warn(`[seed-provinces] COUNTRIES에 없는 등급 이름: ${unknownTier.join(", ")}`);

  const retired = retireProceduralProvinces();

  const tx = db.transaction(() => {
    for (const [countryName, lat, lng] of COUNTRIES) {
      const region = findRegion.get(countryName);
      if (!region || countProvinces.get(region.id).count > 0) continue;

      const plan = buildPlan(countryName, lat, lng);
      const firstDistrictOf = [];
      for (const prov of plan) {
        const provinceId = randomUUID();
        insertProvince.run(provinceId, region.id, prov.name, prov.lat, prov.lng, prov.isCapital ? 1 : 0);
        // 구 난이도: 수도 광역이 제일 단단하고(40) 나머지는 30 — 신규 유저가 변두리부터 깨도록.
        const difficulty = prov.isCapital ? 40 : 30;
        const ids = prov.districts.map(() => randomUUID());
        prov.districts.forEach((d, i) => {
          insertDistrict.run(ids[i], region.id, provinceId, d.name, difficulty, d.lat, d.lng);
        });
        // 광역 안에서는 고리로 인접. 첫 구(중구/첫 시군구)가 광역 간 연결점이 된다.
        for (let i = 0; i < ids.length; i++) link(ids[i], ids[(i + 1) % ids.length]);
        firstDistrictOf.push(ids[0]);
        newProvinces++;
        newDistricts += ids.length;
      }
      // 광역끼리도 고리로 이어 국가 전체가 한 덩어리가 되게 한다(한 곳만 해방하면 어디든 진군 가능).
      for (let i = 0; i < firstDistrictOf.length; i++) {
        link(firstDistrictOf[i], firstDistrictOf[(i + 1) % firstDistrictOf.length]);
      }
    }
  });
  tx();

  invalidateProvinceCache();
  const legacy = retireOrRehomeLegacy();
  const backfilled = backfillPostProvinces();

  console.log(
    `[seed-provinces] 광역 ${newProvinces}곳 / 구 ${newDistricts}곳 추가 · 절차생성 광역 교체 ${retired} · 예전 영토 삭제 ${legacy.removed} / 이전 ${legacy.rehomed} · 기록 광역 배정 ${backfilled}`
  );
}

// 실좌표 데이터가 생긴 국가의 절차생성 광역(중부/북부…)을 걷어낸다. 손 안 탄 구는 지우고, 기록 있는 구는
// province_id를 비워 retireOrRehomeLegacy가 가장 가까운 새 광역으로 옮기게 한다. 반환: 교체한 국가 수.
function retireProceduralProvinces() {
  const procedural = new Set(PROVINCE_ORDER);
  const provincesOf = db.prepare("SELECT p.id, p.name FROM provinces p JOIN regions r ON r.id = p.region_id WHERE r.name = ?");
  const districtsOf = db.prepare("SELECT id, status, dominant_user_id FROM neighborhoods WHERE province_id = ?");
  const touched = db.prepare(
    `SELECT EXISTS(SELECT 1 FROM neighborhood_contributions WHERE neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_attacks WHERE target_neighborhood_id = ? OR from_neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_resistance WHERE neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_founders WHERE neighborhood_id = ?) AS touched`
  );
  const deleteAdjacency = db.prepare("DELETE FROM neighborhood_adjacency WHERE neighborhood_id = ? OR adjacent_neighborhood_id = ?");
  const deleteDistrict = db.prepare("DELETE FROM neighborhoods WHERE id = ?");
  const orphanDistrict = db.prepare("UPDATE neighborhoods SET province_id = NULL WHERE id = ?");
  const orphanPosts = db.prepare("UPDATE map_posts SET province_id = NULL WHERE province_id = ?");
  const deleteProvince = db.prepare("DELETE FROM provinces WHERE id = ?");

  let countries = 0;
  const tx = db.transaction(() => {
    for (const countryName of Object.keys(ADMIN1)) {
      const provs = provincesOf.all(countryName);
      if (!provs.length || !provs.every((p) => procedural.has(p.name))) continue;
      for (const p of provs) {
        for (const d of districtsOf.all(p.id)) {
          const keep = d.status !== "npc" || d.dominant_user_id || touched.get(d.id, d.id, d.id, d.id, d.id).touched;
          if (keep) { orphanDistrict.run(d.id); continue; }
          deleteAdjacency.run(d.id, d.id);
          deleteDistrict.run(d.id);
        }
        orphanPosts.run(p.id);
        deleteProvince.run(p.id);
      }
      countries++;
    }
  });
  tx();
  return countries;
}

// 광역이 없는 예전 영토 처리. 유저 기록이 하나도 없는 행은 장식일 뿐이므로 지우고, 기록이 있으면
// 국가의 수도 광역(도시 시드의 동은 LEGACY_CITY_HOME의 광역) 밑으로 옮긴다.
function retireOrRehomeLegacy() {
  const rows = db
    .prepare(
      `SELECT n.id, n.name, n.status, n.dominant_user_id, n.lat, n.lng, r.name AS region_name, n.parent_region_id
       FROM neighborhoods n JOIN regions r ON r.id = n.parent_region_id
       WHERE n.province_id IS NULL`
    )
    .all();
  if (!rows.length) return { removed: 0, rehomed: 0 };

  const touched = db.prepare(
    `SELECT EXISTS(SELECT 1 FROM neighborhood_contributions WHERE neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_attacks WHERE target_neighborhood_id = ? OR from_neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_resistance WHERE neighborhood_id = ?)
         OR EXISTS(SELECT 1 FROM neighborhood_founders WHERE neighborhood_id = ?) AS touched`
  );
  const deleteAdjacency = db.prepare(
    "DELETE FROM neighborhood_adjacency WHERE neighborhood_id = ? OR adjacent_neighborhood_id = ?"
  );
  const deleteRow = db.prepare("DELETE FROM neighborhoods WHERE id = ?");
  const capitalProvince = db.prepare(
    `SELECT p.id, p.region_id FROM provinces p JOIN regions r ON r.id = p.region_id
     WHERE r.name = ? AND (p.name = ? OR (? IS NULL AND p.is_capital = 1)) LIMIT 1`
  );
  const provinceById = db.prepare("SELECT id, region_id FROM provinces WHERE id = ?");
  const firstDistrict = db.prepare("SELECT id FROM neighborhoods WHERE province_id = ? ORDER BY id LIMIT 1");
  const rehome = db.prepare("UPDATE neighborhoods SET province_id = ?, parent_region_id = ? WHERE id = ?");
  const insertAdjacency = db.prepare(
    "INSERT OR IGNORE INTO neighborhood_adjacency (neighborhood_id, adjacent_neighborhood_id) VALUES (?, ?)"
  );

  let removed = 0;
  let rehomed = 0;
  const tx = db.transaction(() => {
    for (const n of rows) {
      const hasHistory = touched.get(n.id, n.id, n.id, n.id, n.id).touched;
      if (!hasHistory && n.status === "npc" && !n.dominant_user_id) {
        deleteAdjacency.run(n.id, n.id);
        deleteRow.run(n.id);
        removed++;
        continue;
      }
      // 같은 나라 안에서 가장 가까운 광역이 있으면 거기로, 없으면(도시 시드 등) 수도 광역으로.
      let home = null;
      if (n.lat != null && n.lng != null) {
        const near = provinceById.get(nearestProvinceId(n.lat, n.lng) || "");
        if (near && near.region_id === n.parent_region_id) home = near;
      }
      if (!home) {
        const [country, provinceName] = LEGACY_CITY_HOME[n.region_name] || [n.region_name, null];
        home = capitalProvince.get(country, provinceName, provinceName);
      }
      if (!home) continue; // 갈 곳이 없으면 그대로 둔다 — 지우는 것보다 남기는 쪽이 안전하다
      rehome.run(home.id, home.region_id, n.id);
      const anchor = firstDistrict.get(home.id);
      if (anchor && anchor.id !== n.id) {
        insertAdjacency.run(n.id, anchor.id);
        insertAdjacency.run(anchor.id, n.id);
      }
      rehomed++;
    }
  });
  tx();
  return { removed, rehomed };
}

function backfillPostProvinces() {
  const posts = db.prepare("SELECT id, lat, lng FROM map_posts WHERE province_id IS NULL").all();
  if (!posts.length) return 0;
  const update = db.prepare("UPDATE map_posts SET province_id = ? WHERE id = ?");
  const tx = db.transaction(() => {
    for (const p of posts) update.run(nearestProvinceId(p.lat, p.lng), p.id);
  });
  tx();
  return posts.length;
}

